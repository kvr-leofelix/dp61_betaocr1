// Helper to generate full 180-day micro-curriculum data
export function generateCurriculumDays(): CurriculumDay[] {
  const days: CurriculumDay[] = [];
  const chapters = [
    { name: 'Rational Numbers & Operations', core: 14, supp: 6 },
    { name: 'Linear Equations in One Variable', core: 16, supp: 8 },
    { name: 'Understanding Quadrilaterals & Polygons', core: 15, supp: 7 },
    { name: 'Data Handling & Probability', core: 14, supp: 6 },
    { name: 'Squares, Square Roots & Cubes', core: 12, supp: 6 },
    { name: 'Comparing Quantities & Percentage Models', core: 15, supp: 7 },
    { name: 'Algebraic Expressions & Identities', core: 18, supp: 8 },
    { name: 'Mensuration: Surface Areas & Volumes', core: 16, supp: 8 },
    { name: 'Exponents, Powers & Scientific Notation', core: 10, supp: 4 },
    { name: 'Direct & Inverse Proportions', core: 12, supp: 5 },
  ];

  const modalities: Array<'Visual' | 'Auditory' | 'Reading/Writing' | 'Kinesthetic'> = [
    'Visual', 'Auditory', 'Reading/Writing', 'Kinesthetic'
  ];
  const blooms: Array<'Remember' | 'Understand' | 'Apply' | 'Analyze' | 'Evaluate' | 'Create'> = [
    'Remember', 'Understand', 'Apply', 'Analyze', 'Evaluate', 'Create'
  ];

  let currentDay = 1;
  const currentInstructionalDay = 104; // Currently at Day 104

  chapters.forEach((ch, chIdx) => {
    const totalInChapter = ch.core + ch.supp;
    for (let i = 1; i <= totalInChapter && currentDay <= 180; i++) {
      const isCore = i <= ch.core;
      let status: 'completed' | 'in-progress' | 'pending' | 'compressed_to_homework' | 'integrated' = 'pending';
      if (currentDay < currentInstructionalDay) {
        status = 'completed';
      } else if (currentDay === currentInstructionalDay) {
        status = 'in-progress';
      }

      const mod = modalities[(currentDay + chIdx) % modalities.length];
      const bloom = blooms[(i + chIdx) % blooms.length];

      days.push({
        id: `cur-day-${currentDay}`,
        dayNumber: currentDay,
        classId: 'class-8a',
        subjectId: 'sub-math',
        topic: `${ch.name} — Part ${i}: ${isCore ? 'Core Concept & Application' : 'Extension & Supplementary Inquiries'}`,
        objective: isCore
          ? `Master fundamental mastery in ${ch.name} through direct structured modeling and verification.`
          : `Synthesize exploratory case studies and multi-disciplinary contexts in ${ch.name}.`,
        teachingProcess: `Interactive lecture with ${mod.toLowerCase()} activities, group peer review, and formative exit check.`,
        measurableOutcome: `Student can solve 3 target benchmark problems with >80% accuracy within 12 minutes.`,
        estimatedDurationMins: 45,
        varkModality: mod,
        bloomLevel: bloom,
        classification: isCore ? 'core' : 'supplementary',
        status,
        prerequisites: i > 1 ? [`Day ${currentDay - 1}`] : [],
      });
      currentDay++;
    }
  });

  return days;
}

